pub fn imdct_prepare(arr: &[f32]) -> Vec<f32> {
	let mut res = Vec::with_capacity(arr.len() * 2);
	res.extend_from_slice(arr);
	for _ in 0..arr.len() {
		res.push(0.);
	}
	return res;
}

pub fn fuzzy_compare_array(arr_a: &[f32], arr_b: &[f32], epsilon: f32, print_mismatches: bool) -> usize {
	let mut mismatch_cnt: usize = 0;
	for ((idx, entry_a), entry_b) in arr_a.iter().enumerate().zip(arr_b) {
		if (entry_a - entry_b).abs() >= epsilon {
			if print_mismatches {
				println!("Mismatch at idx {}. Expected {} but was {}", idx, entry_a, entry_b);
			}
			mismatch_cnt += 1;
		}
	}
	return mismatch_cnt;
}

