	let _ = writeln!(out, "one an implementation discovers it needed after shipping.\n");

	let _ = writeln!(out, "## Logical, physical and the scale between them\n");
	let _ = writeln!(out, "A surface has THREE sizes and not one. A phone surface is 400 x 800 logical at scale 3.0 and");
	let _ = writeln!(out, "1200 x 2400 physical; an application that cannot see those as three numbers either renders at the");
	let _ = writeln!(out, "wrong size or renders blurred.\n");
	let _ = writeln!(out, "| question | answer |");
	let _ = writeln!(out, "| --- | --- |");
	let _ = writeln!(out, "| how the scale is represented | `{SCALE_REPRESENTATION}` |");
	let _ = writeln!(out, "| which extent is authoritative | {AUTHORITATIVE_EXTENT} |");
	let _ = writeln!(out, "| where an edge lands | {EDGE_RULE} |");
	let _ = writeln!(out, "| how damage rounds | {DAMAGE_ROUNDING} |");
	let _ = writeln!(out, "| how input maps back | {INPUT_MAPPING} |");
	let _ = writeln!(out, "\nThe output transforms are `{}`.\n", TRANSFORMS.join("`, `"));

	let _ = writeln!(out, "## The configuration snapshot\n");
	let _ = writeln!(out, "Configuration arrives as ONE snapshot, atomically. A client never applies a new scale with an old");
	let _ = writeln!(out, "extent, which is what atomic is for.\n");
	let _ = writeln!(out, "| field | invalidates images | why it is in the snapshot |");
	let _ = writeln!(out, "| --- | :---: | --- |");
