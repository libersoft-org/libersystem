	let _ = writeln!(out, "The colour information is `{}` - because a colour-space NAME is not enough to tone map with: a", COLOUR_METADATA.join("`, `"));
	let _ = writeln!(out, "conversion that does not know the destination's luminance is guessing at the one number that decides");
	let _ = writeln!(out, "how the image looks.\n");

	let _ = writeln!(out, "## Events\n");
	let _ = writeln!(out, "| event | carries | why it is its own event |");
	let _ = writeln!(out, "| --- | --- | --- |");
	for event in EVENTS {
		let _ = writeln!(out, "| `{}` | {} | {} |", event.name, event.carries, event.why);
	}
	let _ = writeln!(out, "\n{VISIBILITY_RULE}.\n");

	let _ = writeln!(out, "## The present queue\n");
	let _ = writeln!(out, "| state | meaning |");
	let _ = writeln!(out, "| --- | --- |");
